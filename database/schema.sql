CREATE TABLE IF NOT EXISTS USERS (
    USER_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    FULL_NAME TEXT NOT NULL,
    EMAIL TEXT UNIQUE NOT NULL,
    ROLE TEXT CHECK (ROLE IN ('Student', 'Staff', 'Admin')) DEFAULT 'Student',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS ITEMS (
    ITEM_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    USER_ID INTEGER NOT NULL,
    TITLE TEXT NOT NULL,
    DESCRIPTION TEXT NOT NULL,
    CATEGORY TEXT NOT NULL,
    LOCATION TEXT NOT NULL,
    DATE_EVENT DATE NOT NULL,
    TYPE TEXT CHECK (TYPE IN ('Lost', 'Found')) NOT NULL,
    IMAGE_URL TEXT,
    STATUS TEXT CHECK (STATUS IN ('Open', 'Claimed', 'Matched', 'Closed', 'Archived')) DEFAULT 'Open',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);
CREATE TABLE IF NOT EXISTS CLAIMS (
    CLAIM_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    ITEM_ID INTEGER NOT NULL,
    CLAIMANT_ID INTEGER NOT NULL,
    PROOF_DESCRIPTION TEXT NOT NULL,
    CLAIM_STATUS TEXT CHECK (CLAIM_STATUS IN ('Pending', 'Approved', 'Rejected')) DEFAULT 'Pending',
    FOREIGN KEY (ITEM_ID) REFERENCES ITEMS(ITEM_ID),
    FOREIGN KEY (CLAIMANT_ID) REFERENCES USERS(USER_ID)
);
CREATE TABLE IF NOT EXISTS AUDIT_LOGS (
    LOG_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    USER_ID INTEGER,
    ACTION TEXT NOT NULL,
    DETAILS TEXT,
    TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS HANDOVERS (
    HANDOVER_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    ITEM_ID INTEGER NOT NULL,
    ADMIN_ID INTEGER NOT NULL,
    HANDOVER_NOTE TEXT NOT NULL,
    CLOSED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS CONVERSATIONS (
    CONVERSATION_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    USER_ID INTEGER NOT NULL,
    TITLE TEXT DEFAULT 'New Chat',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS MESSAGES (
    MESSAGE_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    CONVERSATION_ID INTEGER NOT NULL,
    SENDER TEXT CHECK (SENDER IN ('User', 'Assistant')) NOT NULL,
    CONTENT TEXT NOT NULL,
    TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (CONVERSATION_ID) REFERENCES CONVERSATIONS(CONVERSATION_ID)
);
CREATE TABLE IF NOT EXISTS REVIEW_NOTES (
    NOTE_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    CLAIM_ID INTEGER NOT NULL,
    ADMIN_ID INTEGER NOT NULL,
    REVIEW_COMMENT TEXT NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS SYSTEM_META (
    META_KEY TEXT PRIMARY KEY,
    META_VALUE TEXT
);
CREATE TABLE IF NOT EXISTS NOTIFICATIONS (
    NOTIFICATION_ID INTEGER PRIMARY KEY AUTOINCREMENT,
    USER_ID INTEGER NOT NULL,
    MESSAGE TEXT NOT NULL,
    IS_READ INTEGER DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);